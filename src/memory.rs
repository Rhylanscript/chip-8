pub const MEMORY_SIZE: usize = 4096;
pub const PROGRAM_START: usize = 0x200;
pub const FONT_START: usize = 0x50;

// chip8 font set: 0-F, 5b each
const FONT_SET: [u8; 80] = [
    0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
    0x20, 0x60, 0x20, 0x20, 0x70, // 1
    0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
    0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
    0x90, 0x90, 0xF0, 0x10, 0x10, // 4
    0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
    0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
    0xF0, 0x10, 0x20, 0x40, 0x40, // 7
    0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
    0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
    0xF0, 0x90, 0xF0, 0x90, 0x90, // A
    0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
    0xF0, 0x80, 0x80, 0x80, 0xF0, // C
    0xE0, 0x90, 0x90, 0x90, 0xE0, // D
    0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
    0xF0, 0x80, 0xF0, 0x80, 0x80, // F
];

pub struct Memory {
    ram: [u8; MEMORY_SIZE],
}

#[allow(dead_code)]
impl Memory {
    pub fn new() -> Self {
        let mut ram = [0u8; MEMORY_SIZE];
        ram[FONT_START..FONT_START + FONT_SET.len()].copy_from_slice(&FONT_SET);
        Self { ram }
    }

    pub fn load_rom(&mut self, rom_data: &[u8]) {
        let end = PROGRAM_START + rom_data.len();
        assert!(end <= MEMORY_SIZE, "ROM too large to fit in memory");
        self.ram[PROGRAM_START..end].copy_from_slice(rom_data);
    }

    pub fn read(&self, addr: usize) -> u8 {
        self.ram[addr]
    }

    pub fn write(&mut self, addr: usize, value: u8) {
        self.ram[addr] = value;
    }
}
